//! The workspace environment: pullfile `env`, then local.toml `[env]` on top.

use crate::config::{Env, Local, Pullfile};
use anyhow::{Context, Result};
use std::collections::BTreeMap;
use std::ffi::OsString;
use std::path::{Path, PathBuf};

/// Resolved variables to export, in order. `PATH` is complete (new entries + current PATH).
pub fn resolve(root: &Path, pf: &Pullfile, local: Option<&Local>) -> Result<Vec<(String, String)>> {
    let layers: Vec<&Env> = std::iter::once(&pf.env)
        .chain(local.map(|l| &l.env))
        .collect();

    let mut vars: BTreeMap<String, String> = BTreeMap::new();
    vars.insert("PULL_ROOT".into(), root.display().to_string());
    for env in &layers {
        for (k, v) in &env.vars {
            let value = expand(v, &vars);
            vars.insert(k.clone(), value);
        }
    }

    // Local entries first so a machine can shadow the shared toolchain.
    let mut entries: Vec<PathBuf> = Vec::new();
    for env in layers.iter().rev() {
        for p in &env.path {
            let p = PathBuf::from(expand(p, &vars));
            let p = if p.is_relative() { root.join(p) } else { p };
            if !entries.contains(&p) {
                entries.push(p);
            }
        }
    }
    let mut out: Vec<(String, String)> = vars.into_iter().collect();
    if !entries.is_empty() {
        let current = std::env::var_os("PATH").unwrap_or_default();
        let rest = std::env::split_paths(&current).filter(|p| !entries.contains(p));
        let joined: OsString = std::env::join_paths(entries.iter().cloned().chain(rest))
            .context("PATH entry contains a separator")?;
        out.push(("PATH".into(), joined.to_string_lossy().into_owned()));
    }
    Ok(out)
}

fn expand(s: &str, vars: &BTreeMap<String, String>) -> String {
    shellexpand::full_with_context_no_errors(
        s,
        || dirs::home_dir().map(|h| h.display().to_string()),
        |name: &str| vars.get(name).cloned().or_else(|| std::env::var(name).ok()),
    )
    .into_owned()
}

/// POSIX shell `export` lines (bash/zsh/sh; what direnv's `eval` expects).
pub fn exports(vars: &[(String, String)]) -> Result<String> {
    let mut out = String::new();
    for (k, v) in vars {
        let q = shlex::try_quote(v).with_context(|| format!("can't quote value of {k}"))?;
        out.push_str(&format!("export {k}={q}\n"));
    }
    Ok(out)
}

/// direnv `.envrc` that loads the pullfile env and reloads when it changes.
pub const ENVRC: &str = "# generated by `pull env --envrc`: the environment lives in pullfile.plist\n\
watch_file pullfile.plist local.toml\n\
eval \"$(pull env)\"\n";

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn layers_expand_and_path() {
        let mut pf = Pullfile::default();
        pf.env
            .vars
            .insert("TOOLS".into(), "$PULL_ROOT/tools".into());
        pf.env.vars.insert("GOTOOLCHAIN".into(), "local".into());
        pf.env.path = vec!["bin".into(), "$TOOLS".into(), "~/x".into()];
        let mut local = Local::default();
        local
            .env
            .vars
            .insert("GOTOOLCHAIN".into(), "go1.27.4".into());
        local.env.path = vec!["/opt/mine".into()];
        let root = Path::new("/w");
        let v: BTreeMap<_, _> = resolve(root, &pf, Some(&local))
            .unwrap()
            .into_iter()
            .collect();
        assert_eq!(v["PULL_ROOT"], "/w");
        assert_eq!(v["TOOLS"], "/w/tools");
        assert_eq!(v["GOTOOLCHAIN"], "go1.27.4");
        let home = dirs::home_dir().unwrap();
        let path = &v["PATH"];
        let want = format!("/opt/mine:/w/bin:/w/tools:{}/x:", home.display());
        assert!(path.starts_with(&want), "{path}");
        // round-trip through a real shell
        let tricky = "it's $HOME \"q\" `x` \\ end";
        let script = exports(&[("A".into(), tricky.into())]).unwrap() + "printf %s \"$A\"";
        let out = std::process::Command::new("sh")
            .arg("-c")
            .arg(script)
            .output()
            .unwrap();
        assert_eq!(String::from_utf8(out.stdout).unwrap(), tricky);
    }
}
